import './require-node22.mjs';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJiti } from 'jiti';
import { parseDeepDiveSource } from './lib/deep-dive-toc.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const contentDir = join(root, 'content/deep-dives');
const outputPath = join(root, 'src/lib/search/mdx-documents.generated.ts');
const checkOnly = process.argv.includes('--check');
const jiti = createJiti(import.meta.url, {
  alias: {
    '@': join(root, 'src'),
  },
  moduleCache: false,
});
const { CONTENT_ENTRIES } = await jiti.import(join(root, 'src/lib/content/registry.ts'));
const registryByHref = new Map(CONTENT_ENTRIES.map((entry) => [entry.href, entry]));

function toDescription(content) {
  const [sentence] = content.split(/(?<=[.!?])\s+/);
  return sentence && sentence.length <= 180
    ? sentence
    : `${content.slice(0, 177).trim()}...`;
}

function toPlainText(source) {
  return source
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/!\[([^\]]*)\]\([^)]+\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/^import\s+.+$/gm, ' ')
    .replace(/^export\s+.+$/gm, ' ')
    .replace(/[#>*_~|-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const mdxSource = {
  label: 'THORChain Wiki deep-dive source',
  url: 'https://github.com/Reedtrullz/tcwiki/tree/main/content/deep-dives',
};

const documents = readdirSync(contentDir)
  .filter((file) => file.endsWith('.mdx'))
  .sort()
  .flatMap((file) => {
    const slug = file.replace(/\.mdx$/, '');
    const slugPath = `/deep-dives/${slug}`;
    const source = readFileSync(join(contentDir, file), 'utf8');
    const parsed = parseDeepDiveSource(source);
    const content = toPlainText(source);
    const registryEntry = registryByHref.get(slugPath);
    const metadata = {
      confidence: registryEntry?.confidence ?? 'curated',
      reviewedAt: registryEntry?.reviewedAt ?? '2026-07-02',
      nextReviewDue: registryEntry?.nextReviewDue ?? '2026-08-02',
      sources: registryEntry?.sources ?? [mdxSource],
    };
    const title = parsed.title ?? slug
      .split('-')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(' ');

    return [
      {
        id: `mdx:${slug}`,
        slug: slugPath,
        href: slugPath,
        type: 'deep-dive',
        title,
        description: toDescription(content),
        ...metadata,
        content,
      },
      ...parsed.sections.map((section) => ({
        id: `deep-dive-section:${slug}:${section.id}`,
        slug: slugPath,
        href: `${slugPath}#${section.id}`,
        anchor: section.id,
        type: 'deep-dive-section',
        title: section.title,
        description: toDescription(section.content),
        content: section.content,
      })),
    ];
  });

const generated = `// Generated by scripts/generate-mdx-search.mjs. Do not edit by hand.
import type { MdxSectionSearchDocument, SearchDoc } from '@/lib/search/registry';

export const MDX_SEARCH_DOCUMENTS: SearchDoc[] = ${JSON.stringify(documents.filter((document) => document.type === 'deep-dive'), null, 2)};
export const MDX_DEEP_DIVE_SECTION_DOCUMENTS: MdxSectionSearchDocument[] = ${JSON.stringify(documents.filter((document) => document.type === 'deep-dive-section'), null, 2)};
`;

if (checkOnly) {
  const existing = readFileSync(outputPath, 'utf8');
  if (existing !== generated) {
    console.error(`${relative(root, outputPath)} is stale. Run npm run generate:search.`);
    process.exit(1);
  }
  console.log('MDX search document generation is current.');
} else {
  writeFileSync(outputPath, generated);
  console.log(`Wrote ${relative(root, outputPath)}.`);
}
